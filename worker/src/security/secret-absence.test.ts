import { appendFileSync, mkdtempSync, mkdirSync, readFileSync, renameSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Readable } from "node:stream";
import type { IncomingMessage, ServerResponse } from "node:http";

import { afterAll, describe, expect, it } from "vitest";

import {
  assertSecretsAbsent,
  scanSecretAbsence,
} from "./secret-absence.js";
import { devRedactedRequestSnapshot } from "../providers/chatgpt-oauth/dev-snapshot.js";
import { BrowserOAuthError } from "../providers/chatgpt-oauth/auth.js";
import { isTrustedAppOrigin } from "../server/app-origin.js";
import { boundedTraceRecord, type TraceRecord } from "../traces/store.js";
import { handleChatGptOAuthRoute, installChatGptOAuthRouteRuntime } from "../server/chatgpt-oauth-routes.js";

const stage = mkdtempSync(join(tmpdir(), "supertwin-secret-absence-"));
const corpus = ["traces", "logs", "snapshots", "api-responses"].map((name) => join(stage, name));
for (const root of corpus) mkdirSync(root, { recursive: true });

const secrets = {
  access_token: "access.synthetic.7xN0HcsQFAJv",
  refresh_token: "refresh.synthetic.qV3aP1Km8ZRt",
  authorization_code: "code-synthetic-4Dq8xL1p",
  pkce_verifier: "verifier-synthetic-R6m2K9wQ",
  oauth_state: "state-synthetic-Y7b3N5cV",
  account_id: "acct-synthetic-J4h8T2pM",
};

afterAll(async () => {
  installChatGptOAuthRouteRuntime(null);
  const { rmSync } = await import("node:fs");
  rmSync(stage, { recursive: true, force: true });
});

describe("P6-E bounded secret-absence corpus", () => {
  it("passes artifacts generated by the real trace, error, snapshot and API projections", async () => {
    const trace: TraceRecord = {
      trace_id: "security-trace", ts: "2026-09-09T00:00:00Z", run_id: "security-run",
      attempt: 1, pass: "security", caller: "security-test", model: "gpt-test", prompt_version: null,
      system_prompt: "safe", packed_context: "safe", raw_output: "safe", parsed_result: null,
      repair_count: 0, verdicts: null, tokens_4way: { input: 0, cache_creation: 0, cache_read: 0, output: 0 },
      cost_usd: null, latency_ms: 0, status: "ok",
    };
    writeFileSync(join(corpus[0]!, "day.jsonl"), `${JSON.stringify(boundedTraceRecord(trace))}\n`);
    writeFileSync(join(corpus[1]!, "worker.log"), `${new BrowserOAuthError("BAD_REQUEST", "OAuth callback was invalid").message}\n`);
    const snapshot = devRedactedRequestSnapshot({
      runId: "security-snapshot", model: "gpt-test", instructions: secrets.access_token,
      input: [{ type: "function_call_output", call_id: "call-safe", output: secrets.refresh_token }],
      continuation: { token: secrets.authorization_code },
      cache: { mode: "explicit", key: secrets.pkce_verifier },
      maxOutputTokens: 64, maxAgentTurns: 1, onEvent: () => undefined,
    });
    writeFileSync(join(corpus[2]!, "request.json"), JSON.stringify(snapshot));
    installChatGptOAuthRouteRuntime({
      status: () => ({ authState: { status: "ready", error: null }, plan: "Plus",
        quota: { state: "available", resetAt: null }, tokenExpiresAt: null,
        canary: { status: "passed", checkedAt: null, error: null } }),
      start: async () => { throw new Error("unused"); },
      snapshot: () => ({ loginId: null, status: "idle", expiresAt: null, error: null }),
      cancel: async () => false, logout: async () => undefined,
    });
    const req = Readable.from([]) as unknown as IncomingMessage;
    Object.assign(req, { method: "GET", url: "/api/providers/chatgpt-oauth/status" });
    let apiPayload = "";
    const res = { writeHead() { return this; }, end(value?: string) { apiPayload = value ?? ""; } } as unknown as ServerResponse;
    await handleChatGptOAuthRoute(req, res);
    writeFileSync(join(corpus[3]!, "status.json"), apiPayload);
    expect(assertSecretsAbsent({ roots: corpus, secrets })).toMatchObject({ files: 4, findings: [] });
  });

  it("allows only the shipped origin in production and one exact development origin", () => {
    const before = process.env.NODE_ENV;
    const beforeOrigin = process.env.SUPERTWIN_DEV_ORIGIN;
    try {
      process.env.NODE_ENV = "production";
      expect(isTrustedAppOrigin("tauri://localhost")).toBe(true);
      expect(isTrustedAppOrigin("http://localhost:1420")).toBe(false);
      expect(isTrustedAppOrigin("https://localhost:1420")).toBe(false);
      process.env.NODE_ENV = "test";
      expect(isTrustedAppOrigin("http://localhost:1420")).toBe(false);
      process.env.NODE_ENV = "development";
      process.env.SUPERTWIN_DEV_ORIGIN = "http://localhost:1420";
      expect(isTrustedAppOrigin("http://localhost:1420")).toBe(true);
      expect(isTrustedAppOrigin("http://localhost:1421")).toBe(false);
    } finally {
      if (before === undefined) delete process.env.NODE_ENV; else process.env.NODE_ENV = before;
      if (beforeOrigin === undefined) delete process.env.SUPERTWIN_DEV_ORIGIN; else process.env.SUPERTWIN_DEV_ORIGIN = beforeOrigin;
    }
  });

  it.each(Object.entries(secrets))("detects synthetic %s without exposing its value", (name, value) => {
    const file = join(corpus[1]!, `leak-${name}.log`);
    writeFileSync(file, `unsafe=${value}\n`);
    const result = scanSecretAbsence({ roots: [file], secrets });
    expect(result.findings).toContainEqual({ file, secret: name, encoding: "plain" });
    expect(JSON.stringify(result.findings)).not.toContain(value);
  });

  it("detects URL and base64 representations", () => {
    const value = "secret with / callback?code=1";
    const file = join(corpus[2]!, "encoded.txt");
    writeFileSync(file, `${encodeURIComponent(value)}\n${Buffer.from(value).toString("base64")}\n`);
    expect(scanSecretAbsence({ roots: [file], secrets: { callback_secret: value } }).findings)
      .toEqual(expect.arrayContaining([
        expect.objectContaining({ encoding: "url" }),
        expect.objectContaining({ encoding: "base64" }),
      ]));
  });

  it.each([
    ["utf16le", (value: string) => Buffer.from(value, "utf16le")],
    ["utf16be", (value: string) => { const data = Buffer.from(value, "utf16le"); data.swap16(); return data; }],
    ["base64url", (value: string) => Buffer.from(Buffer.from(value).toString("base64url"))],
    ["json-unicode", (value: string) => Buffer.from([...value].map((char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`).join(""))],
    ["lower-percent", (value: string) => Buffer.from(encodeURIComponent(value).replace(/%[0-9A-F]{2}/g, (part) => part.toLowerCase()))],
  ])("detects %s equivalents", (_label, encode) => {
    const value = "secret /+?= synthetic";
    const file = join(corpus[2]!, `equivalent-${_label}.bin`);
    writeFileSync(file, encode(value));
    expect(scanSecretAbsence({ roots: [file], secrets: { equivalent: value } }).findings.length).toBeGreaterThan(0);
  });

  it("fails closed on file and byte bounds and never follows symlinks", () => {
    const outside = join(stage, "outside.txt");
    writeFileSync(outside, secrets.access_token);
    const link = join(corpus[0]!, "outside-link");
    symlinkSync(outside, link);
    expect(scanSecretAbsence({ roots: [link], secrets }).findings).toEqual([]);
    expect(() => scanSecretAbsence({ roots: corpus, secrets, maxFiles: 1 })).toThrow("file limit");
    expect(() => scanSecretAbsence({ roots: [outside], secrets, maxFileBytes: 1 })).toThrow("per-file limit");
  });

  it("detects descriptor growth and is immune to pathname replacement after open", () => {
    const growing = join(stage, "growing.log");
    writeFileSync(growing, "safe-start");
    expect(() => scanSecretAbsence({ roots: [growing], secrets, onFileOpened: () => appendFileSync(growing, "growth") }))
      .toThrow("changed during read");

    const swapping = join(stage, "swapping.log");
    const original = join(stage, "opened-original.log");
    writeFileSync(swapping, "safe original artifact");
    const result = scanSecretAbsence({ roots: [swapping], secrets, onFileOpened: () => {
      renameSync(swapping, original);
      writeFileSync(swapping, secrets.access_token);
    } });
    expect(result.findings).toEqual([]);
  });

  it("fails closed when a directory is replaced by a symlink during enumeration", () => {
    const directory = join(stage, "directory-swap");
    const original = join(stage, "directory-original");
    const replacement = join(stage, "directory-replacement");
    mkdirSync(directory); mkdirSync(replacement);
    writeFileSync(join(directory, "safe.log"), "safe");
    expect(() => scanSecretAbsence({ roots: [directory], secrets, onDirectoryOpened: (opened) => {
      if (opened !== directory) return;
      renameSync(directory, original);
      symlinkSync(replacement, directory);
    } })).toThrow("directory changed");
  });

  it.each(["utf16le", "utf16be"] as const)("finds odd-length prefixed and suffixed %s", (encoding) => {
    const value = "aligned-synthetic-secret";
    let body = Buffer.from(value, "utf16le");
    if (encoding === "utf16be") { body = Buffer.from(body); body.swap16(); }
    for (const [label, framed] of [["prefix", Buffer.concat([Buffer.from([0xff]), body])],
      ["suffix", Buffer.concat([body, Buffer.from([0xff])])]] as const) {
      const file = join(corpus[2]!, `${encoding}-${label}.bin`);
      writeFileSync(file, framed);
      expect(scanSecretAbsence({ roots: [file], secrets: { aligned: value } }).findings)
        .toEqual(expect.arrayContaining([expect.objectContaining({ encoding })]));
    }
  });

  it("keeps production auth free of device-code, API-key and Codex CLI imports", () => {
    const worker = join(dirname(fileURLToPath(import.meta.url)), "..");
    const entries = [
      "providers/chatgpt-oauth/auth.ts",
      "providers/chatgpt-oauth/index.ts",
      "providers/chatgpt-oauth/runtime.ts",
      "server/chatgpt-oauth-routes.ts",
    ];
    const pending = entries.map((entry) => join(worker, entry));
    const visited = new Set<string>();
    while (pending.length > 0) {
      const file = pending.pop()!;
      if (visited.has(file)) continue;
      visited.add(file);
      const source = readFileSync(file, "utf8");
      expect(source).not.toMatch(
        /from\s+["'][^"']*device-flow|OPENAI_API_KEY|openai_api_key|(?:spawn|execFile)\s*\([^\n]*codex|providerId:\s*["']codex-cli/i,
      );
      for (const match of source.matchAll(/(?:from\s+|import\s*\()["'](\.{1,2}\/[^"']+)["']/g)) {
        const imported = resolve(dirname(file), match[1]!).replace(/\.js$/, ".ts");
        expect(imported).not.toContain("/probe/");
        try { readFileSync(imported); pending.push(imported); } catch { /* type-only/package asset */ }
      }
    }
    expect(visited.size).toBeGreaterThan(entries.length);
  });
});
