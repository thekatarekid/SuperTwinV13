// ===========================================================================
// [LLM-M] P-CL1 — claims + loops — arch §12.4. Build item 3.1.
//
// THE CORE CALL. One call per episode batch, and it answers three questions
// that are never traded against each other (§11.3, the containment rule):
//
//     every EPISODE ──► ONE understanding call
//                        ├─ always ─────► CLAIMS   (8 kinds, the TAG is the kind)
//                        ├─ intent + an ► LOOPS    (four generators, only)
//                        │  unresolved end
//                        └─ always ─────► Y SUMMARY (2–3 sentences)
//
// FIVE THINGS THIS FILE HOLDS
//
//   THE CLAIM KIND IS THE TAG.  `F P B O I R H W` — eight kinds for one
//        character, no `kind` field anywhere on the wire and none in the
//        parser. §5.3. An unknown tag is a violation, never a guess.
//
//   BOTH OUTPUTS, ALWAYS.  "For EVERY episode produce TWO independent outputs.
//        Never choose between them." Evidence of state is a claim; evidence of
//        intent is a loop; a sentence that carries both produces both.
//
//   THE Y LINE IS WHAT MAKES DELTA MODE FREE.  Pass 1 emits the episode
//        summary, so P-CL1Δ's default `summary` context mode costs ~20 % of a
//        full call without a second summarisation call anywhere (§12.5).
//
//   RELATIVE TIME IS THE EPISODE'S, NOT TODAY'S.  Episodes arrive out of
//        chronological order by design (newest-first import), so "the 28th"
//        resolves against the `#D` block the event sits in. The packer prints
//        that date; the prompt names it; nothing here reads a clock.
//
//   PARTY_PAIR IS NEVER ON THE WIRE.  §5.4. Code derives so/oo from the
//        resolved aliases and the session participant set (§4.5) — the model
//        is never asked, so it can never be wrong about it.
//
// Nothing here writes a row. This module builds the call; `claims/extract.ts`
// reads the answer and `claims/write.ts` (item 3.3) disposes.
// ===========================================================================

import { packPrompt, type PackInput, type PackOptions, type PackResult } from "../wire/pack.js";
import type { AliasTable } from "../wire/aliases.js";
import { legendFor } from "./legend.js";

/** §12.4 "Settings", transcribed. */
export const P_CL1 = {
  id: "P-CL1",
  /** A valid `runs.role` (§4.4.4.4) — claims and loops are extraction spend. */
  role: "extract",
  model: "sonnet-5",
  /** "plain · 1 turn". */
  turns: 1,
  /** "tools none" — this call reads what it is given and nothing else. */
  tools: "none",
  /** "thinking off": a fixed output grammar gains nothing from reasoning tokens. */
  thinking: "off",
  /** "180 s". */
  timeoutSeconds: 180,
  /** "≤4 episodes / 10k in" — whichever cap is hit first closes the call. */
  maxEpisodesPerCall: 4,
  maxInputTokens: 10_000,
  /** "6,000 max out". */
  maxOutputTokens: 6_000,
} as const;

/**
 * The tags this call may emit (§5.3). Anything else is counted by the parser
 * and kept verbatim — never applied, never deleted.
 *
 * The eight claim tags are listed before `T` so the legend prints them as one
 * shape group, which is exactly the point §5.3 makes: the kind IS the tag.
 */
export const P_CL1_TAGS = ["Y", "F", "P", "B", "O", "I", "R", "H", "W", "T", "Q"] as const;

/** §12.4 SYSTEM, verbatim. */
export const P_CL1_SYSTEM = `You extract structured memory from one person's life data.

For EVERY episode produce TWO independent outputs. Never choose between them.

A) CLAIMS — always. Every descriptive statement about any entity.
   The TAG is the kind:
     F fact   P preference   B belief   O opinion
     I interest   R recommendation   H habit   W workflow
   - Subject MUST be a roster alias, or "-" with a hint. UNKNOWN BEATS WRONG.
     Write the hint as "+<hint>" in the subject field: "+Rohan Mehta" when you
     know the name but it is not on the roster, "+Pranjali's landlord" when a
     description is all you have. A bare "-" is for a subject you cannot even
     describe. NEVER pick the nearest roster alias to avoid a blank.
   - Write every claim in RESOLVED THIRD PERSON. Never leave "me", "she",
     "there" unresolved. If self says "I love X", the subject is me and the
     text is "Loves X".
   - attribution: 1p first-person · ao about-other · rs reported speech ·
     q3 quoted/forwarded content the speaker did not author
   - valid_from only when the episode states a time bound.
   - No claims for logistics chatter ("ok", "sent", "reaching").

B) LOOPS — ONLY when BOTH are present: evidence of INTENT and an UNRESOLVED
   END STATE. Generated by exactly one of:
     1. an explicit commitment with an open end
     2. a fact with a TEMPORAL BOUNDARY — lease, passport, warranty, renewal,
        subscription, policy, appointment. These are the highest-value loops
        in old data. Extract them wherever they appear.
     3. a recurring obligation
     4. the user declaring one
   - origin ex when stated by anyone present, im when you inferred it.
     Be conservative with im: a false suggestion costs more than a missed one.
   - due: ISO date, or "-". NEVER invent one. "soon"/"next week" → "-" unless
     the episode fixes it. Resolve relative dates against the EPISODE's date.
   - recurrence when the obligation repeats (monthly, annual, weekly).
   - NO loop for something you merely could help with — that is a capability
     guess, not the person's intent.
   - NO loop for a recommendation someone made. That is an R claim. It becomes
     a loop only when the user commits.

C) SUMMARY — one Y line per episode, 2-3 self-contained sentences. It is reused
   as context when this episode is re-read later. Describe, do not editorialise.

HARD RULES
- Cite ONLY roster aliases. Every claim and loop MUST cite ≥1 event.
- Speakers are given. Never infer or contradict them.
- Episodes arrive out of chronological order by design. Judge only from what
  this episode says, using the episode's own date for relative time.
- Placeholders are UNKNOWN content, never empty and never an acknowledgement.

OUTPUT
  Y | <ep> | <summary>
  F | <events> | <subject> | <attribution> | <conf> | <valid_from> | <text>
      P B O I R H W are identical in shape
  T | <events> | <owner> | <cpty> | <origin> | <dir> | <stake> | <horizon>
    | <due> | <recurrence> | <conf> | <intent>
  Q | <about> | <question>
Values: attribution 1p|ao|rs|q3 · origin ex|im · dir i2t|t2i|shr|slf
        stake h|m|l · horizon d|w|mo|q|y|n
State, triage and party_pair are NEVER yours to write. Code derives all three.`;

/** The memoised legend for this call type (§5.9.4) — rendered, never copied. */
export function cl1Legend(): string {
  return legendFor({
    callType: P_CL1.id,
    tags: [...P_CL1_TAGS],
    aliases: ["entity", "stream", "episode", "loop"],
  });
}

/**
 * legend + §12.4 SYSTEM. Byte-identical on every call, which is the whole
 * reason the instruction half is a cache candidate at all (§4.4.3.2, §5.9.4).
 */
export function buildCl1System(): string {
  return [cl1Legend(), P_CL1_SYSTEM].join("\n\n");
}

// ---- the call --------------------------------------------------------------

export interface Cl1Prompt {
  system: string;
  user: string;
  /**
   * The prompt-local alias table (§5.2). It is the ONLY thing the answer may
   * be read against, and it is thrown away with the response.
   */
  table: AliasTable;
  /** The packer's own report — roster size, streams, events, day blocks. */
  stats: Extract<PackResult, { ok: true }>["stats"];
}

/**
 * Build the call.
 *
 * The USER half is the ordinary packer's output (§5.5), so P-CL1's input is
 * byte-for-byte the shape §12.4 shows: `#R` roster, `#C` stream header, `#T`
 * open loops (supplied as context and correctly NOT re-emitted), `#D` date +
 * timezone, the event lines, `#COV` coverage.
 *
 * A roster over the packer's cap comes back as `null` rather than a truncated
 * prompt: a silently halved roster is how a model gets blamed for attributing
 * a claim to the wrong Amit (§5.9.3 — that call falls back and is logged).
 */
export function buildCl1Prompt(input: PackInput, options: PackOptions = {}): Cl1Prompt | null {
  const packed = packPrompt(input, options);
  if (!packed.ok) return null;
  return {
    system: buildCl1System(),
    user: packed.text,
    table: packed.table,
    stats: packed.stats,
  };
}

/** The provider knobs §12.4 fixes. Built here so no call site can raise them. */
export interface Cl1SendShape {
  model: string;
  maxTurns: number;
  timeoutMs: number;
  maxOutputTokens: number;
  thinkingBudget: "off";
  /** No tools: a plain completion, not an agent turn. */
  plainCompletion: true;
}

export function cl1SendOptions(): Cl1SendShape {
  return {
    model: P_CL1.model,
    maxTurns: P_CL1.turns,
    timeoutMs: P_CL1.timeoutSeconds * 1_000,
    maxOutputTokens: P_CL1.maxOutputTokens,
    thinkingBudget: "off",
    plainCompletion: true,
  };
}

/**
 * Split episodes into calls at the §12.4 cap. Batching is a caller concern —
 * this only enforces "≤4 episodes", so no code path can quietly send five.
 */
export function cl1Batches<T>(episodes: readonly T[], cap: number = P_CL1.maxEpisodesPerCall): T[][] {
  const size = Math.max(1, Math.floor(cap));
  const out: T[][] = [];
  for (let i = 0; i < episodes.length; i += size) out.push(episodes.slice(i, i + size));
  return out;
}
