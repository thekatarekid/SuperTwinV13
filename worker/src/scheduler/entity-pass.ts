/**
 * How many times one event is retried before it is quarantined and the rest of
 * the backlog is allowed to keep moving. Quarantine is per-unit by design
 * (§9.7): one unreadable actor must not stall 3,000 readable ones.
 */
export const ENTITY_MAX_ATTEMPTS = 3;

/** How many same-name candidates one mint is checked against. Bounded, like §11.1's. */
export const MAX_ENTITY_CANDIDATES = 8;

function log(line: string): void {
  console.error(`[entity] ${line}`);
}

// ---------------------------------------------------------------------------
// Reading an identity kind off a value
// ---------------------------------------------------------------------------

const JID_DOMAINS = new Set(["s.whatsapp.net", "c.us", "whatsapp.net", "g.us", "lid"]);
const EMAIL = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
const PHONE = /^\+?\d{6,15}$/;

/**
 * Which `IdentityKind` this value IS. Deliberately read off the value's own
 * shape rather than off a source's configuration: a jid domain, an `@` with a
 * TLD behind it and a run of 6–15 digits are FACTS about the string, the same
 * exactness `phoneFromJid` works at, and a source-level default would mislabel
 * the one actor that does not look like its siblings.
 *
 * The manifest breaks the remaining tie and only that tie: an unrecognised
 * shape takes the source's kind when the manifest emits exactly ONE, and
 * otherwise falls to `handle` — which never binds across sources (§10.3 rule
 * 1), so the conservative answer is also the safe one.
 */
export function identityKindOf(sourceId: string | null, value: string): IdentityKind {
  const text = String(value ?? "").trim();
  const at = text.lastIndexOf("@");
  if (at > 0) {
    const domain = text.slice(at + 1).toLowerCase();
    if (JID_DOMAINS.has(domain)) return "jid";
    if (EMAIL.test(text)) return "email";
  }
  if (PHONE.test(text)) return "phone";
  const emitted = sourceId === null ? undefined : getManifest(sourceId)?.identities_emitted;
  return emitted?.length === 1 ? emitted[0] : "handle";
}

/**
 * A display name worth carrying onto an entity. The ingest path already refuses
 * to overwrite a real name with a jid-looking placeholder; this is the same
 * rule at the other end — `canonical` is what a human reads, and a jid is not
 * one.
 */
function usableName(raw: string | null): string | null {
  const name = String(raw ?? "").trim();
  if (name === "" || name.includes("@")) return null;
  return name;
}

// ---------------------------------------------------------------------------
// `me` — §10.3 rule 4, before anything else
// ---------------------------------------------------------------------------

const SELF_SUFFIX = ".self_identity";

export interface SelfBinding {
  sourceId: string;
  entityId: string;
  kind: IdentityKind;
  value: string;
}

/**
 * Bind every source's persisted `self_identity` into the one `me` entity.
 *
 * The DB is asked, not the adapter registry: `app_state` is where the daemon
 * writes the self jid at pairing, it survives a boot with no adapters
 * registered (every test, and any worker that never got as far as
 * `registerSource`), and it is already set on a live install — so self binding
 * works on the VERY FIRST pass, which is the whole reason attribution is
 * fixable at all. The registry is consulted only for the identity kind, and
 * only when the value's own shape did not answer.
 */
export function bindSelfIdentities(): SelfBinding[] {
  ensureMeEntity();
  const rows = getDb()
    .prepare(
      `SELECT key, value FROM app_state
        WHERE key LIKE 'source.%' AND key LIKE '%' || ? AND NULLIF(TRIM(value), '') IS NOT NULL
        ORDER BY key`,
    )
    .all(SELF_SUFFIX) as { key: string; value: string }[];

  const bound: SelfBinding[] = [];
  for (const row of rows) {
    const sourceId = row.key.slice("source.".length, row.key.length - SELF_SUFFIX.length);
    if (sourceId === "") continue;
    const value = row.value.trim();
    const manifestKind = getManifest(sourceId)?.self_identity.kind;
    const kind: IdentityKind = manifestKind ?? identityKindOf(sourceId, value);
    if (normaliseIdentityValue(kind, value) === "") continue;
    bound.push({ sourceId, kind, value, entityId: bindSelfIdentity({ sourceId, kind, value }) });
  }
  return bound;
}

/** The `me` entity id, creating it if this install has never had one. */
export function selfEntityId(): string {
  return meEntityId() ?? ensureMeEntity();
}

// ---------------------------------------------------------------------------
// One actor → one entity
// ---------------------------------------------------------------------------

interface ActorRow {
  id: string;
  source_id: string | null;
  source_ext_id: string | null;
  display_name: string | null;
  handle: string | null;
}

/**
 * Entities that already carry this exact name, newest first — the candidate
 * set a MINT is checked against. Exact on the NORMALISED name and nothing
 * fuzzier: a candidate is a question worth asking, and asking it about every
 * near-miss is how a bootstrap fills the resolution queue with noise.
 *
 * Tombstones are excluded (`merged_into IS NULL`): a merged entity is not a
 * second entity, and proposing one is proposing a merge that already happened.
 */
function nameCandidates(name: string | null, exclude: string): string[] {
  const want = normaliseIdentityValue("alias", name ?? "");
  if (want === "") return [];
  const rows = getDb()
    .prepare(
      `SELECT id FROM entities
        WHERE merged_into IS NULL AND canonical IS NOT NULL
          AND LOWER(TRIM(canonical)) = ? AND id <> ?
        ORDER BY COALESCE(last_seen_at, created_at) DESC, id
        LIMIT ?`,
    )
    .all(want, exclude, MAX_ENTITY_CANDIDATES) as { id: string }[];
  return rows.map((r) => r.id);
}

export interface ActorResolution {
  actorId: string;
  entityId: string;
  /** `exact` · `cross_source` · `mint`, or the rung an escalation reached. */
  rung: string;
  minted: boolean;
  /** Pairs parked on the agent batch for the horizon boundary. Never called here. */
  deferred: number;
  /** Pairs sent to the human resolution queue — rung ⑤. */
  queued: number;
}

export interface EntityPassOptions {
  now?: number;
  runId?: string | null;
  /** Where in-band pairs wait for the batched agent lane. Defaults to the bootstrap batch. */
  batch?: AgentBatch;
  /** False when no agent lane exists at all — pairs fold to the human queue. */
  agentAvailable?: boolean;
  /**
   * True on the path the user is waiting on. Bars rung ④ outright (§10.3:
   * the agent is never on the first-paint path) — the pair becomes a question
   * instead of a deferral.
   */
  firstPaint?: boolean;
  mode?: SchedulerMode;
  /** Which horizon a parked pair belongs to — the unit `flushAgentBatch` drains. */
  horizon?: Horizon;
}

function ladderContext(opts: EntityPassOptions): Omit<PairContext, "left" | "right" | "score"> {
  return {
    ...(opts.mode === undefined ? {} : { mode: opts.mode }),
    ...(opts.horizon === undefined ? {} : { horizon: opts.horizon }),
    firstPaint: opts.firstPaint === true,
    agentAvailable: opts.agentAvailable !== false,
  };
}

/**
 * The whole ladder for one actor. Rungs ① and ② bind exactly and free; a MINT
 * is escalated over its same-name candidates, and every escalation that
 * reaches rung ④ is PARKED, never called — `resolveIdentity` cannot reach the
 * network by construction (see `resolve.ts`'s header) and neither can this.
 *
 * Null when the actor row is missing or carries no external identity at all.
 * `actor_raw` is deliberately not a fallback: a name string is never an id.
 */
export function resolveActorEntity(actorId: string, opts: EntityPassOptions = {}): ActorResolution | null {
  const row = getDb()
    .prepare(`SELECT id, source_id, source_ext_id, display_name, handle FROM actors WHERE id = ?`)
    .get(actorId) as ActorRow | undefined;
  if (row === undefined) return null;
  const value = String(row.source_ext_id ?? "").trim();
  if (value === "") return null;

  const sourceId = row.source_id ?? null;
  const kind = identityKindOf(sourceId, value);
  if (normaliseIdentityValue(kind, value) === "") return null;
  const displayName = usableName(row.display_name);

  // The candidate set is read BEFORE the bind, because a bind that mints is
  // itself a same-name row and would otherwise be its own candidate.
  const candidates = nameCandidates(displayName, "");
  const resolution = resolveIdentity({
    sourceId: sourceId ?? "",
    kind,
    value,
    type: "person",
    displayName,
    candidates,
    ladder: ladderContext(opts),
    apply: { batch: opts.batch ?? bootstrapAgentBatch, runId: opts.runId ?? null },
  });

  return {
    actorId,
    entityId: resolution.bind.entityId,
    rung: resolution.rung,
    minted: resolution.bind.minted,
    deferred: resolution.escalations.filter((e) => e.outcome === "deferred").length,
    queued: resolution.escalations.filter((e) => e.outcome === "queued").length,
  };
}

