/**
 * Events still waiting on identity binding — the catch-up query, and what
 * `planBootstrap` projects the stage off.
 *
 * "Waiting" is a property of the ROWS (`actor_entity_id IS NULL`), not a
 * memory of having run: a kill -9 mid-drain costs the in-flight event and
 * nothing else. Reactions are excluded for the same reason `tiers/rescan.ts`
 * excludes them from `pendingEvents` — the two queries must agree about what
 * the lane owes or the meter never reaches its own total.
 */
export function pendingEntityWork(opts: { limit?: number } = {}): string[] {
  const limit = Math.max(1, Math.floor(opts.limit ?? 500));
  const rows = getDb()
    .prepare(
      `SELECT e.id AS id
         FROM events e
        WHERE e.actor_entity_id IS NULL
          AND e.kind IS NOT 'reaction'
          AND NOT EXISTS (SELECT 1 FROM work_queue w
                           WHERE w.stage = 'entity' AND w.unit_kind = 'event'
                             AND w.unit_id = e.id AND w.state = 'done')
        ORDER BY e.ts DESC, e.id
        LIMIT ?`,
    )
    .all(limit) as { id: string }[];
  return rows.map((r) => r.id);
}

/** §9.3 priority for one event, off its stream's tier and its recency. */
function eventPriority(eventId: string, now: number): number {
  const row = getDb()
    .prepare(
      `SELECT e.ts AS ts, st.tier AS tier
         FROM events e LEFT JOIN streams st ON st.id = e.stream_id
        WHERE e.id = ?`,
    )
    .get(eventId) as { ts: string | null; tier: string | null } | undefined;
  const rawTier = row?.tier;
  const tier: Tier = isTier(rawTier) ? rawTier : "T3";
  const ts = row?.ts ?? now;
  return computePriority({ tier, horizon: horizonFor(ts, now), ts, now });
}

/**
 * Put events on the shared queue at stage `entity`.
 *
 * ⚠ `tiers/rescan.ts` writes its lane-entry rows under the id `wq:<stage>:<id>`
 * while `queue.ts`'s own `workId` says `wq:<stage>:<unitKind>:<id>`. The two
 * spellings are DIFFERENT PRIMARY KEYS for the same unit-stage, so an
 * unguarded `enqueueWork` here would give half the backlog a second row and
 * bind every one of those events twice. The real key is
 * `(stage, unit_kind, unit_id)`, so that is what is asked about: an event that
 * already has a row a lane can reach is left exactly where it is.
 */
export function enqueueEntityWork(
  eventIds: readonly string[],
  opts: { cohortId?: string | null; now?: number } = {},
): EnqueueOutcome[] {
  const now = opts.now ?? Date.now();
  const existing = getDb().prepare(
    `SELECT 1 AS hit FROM work_queue
      WHERE stage = 'entity' AND unit_kind = 'event' AND unit_id = ?
        AND state IN ('ready', 'running', 'done') LIMIT 1`,
  );
  const out: EnqueueOutcome[] = [];
  for (const eventId of eventIds) {
    if (existing.get(eventId) !== undefined) continue;
    out.push(
      enqueueWork({
        unitKind: "event",
        unitId: eventId,
        stage: "entity",
        priority: eventPriority(eventId, now),
        cohortId: opts.cohortId ?? null,
      }),
    );
  }
  return out;
}

export interface EntityDrainReport {
  claimed: number;
  /** Events whose `actor_entity_id` (and derived `is_self`) was written. */
  bound: number;
  /** Distinct actors resolved this drain — 3,141 events, 100 of these. */
  actorsResolved: number;
  /** Entities minted because nothing matched. */
  minted: number;
  /** Events bound to the `me` entity — the number attribution depends on. */
  selfBound: number;
  /** Sources whose `self_identity` was bound into `me` this pass. */
  selfSources: number;
  /**
   * Events left unbound because the row carries no structural actor at all.
   * Their queue rows are marked `done`: a name string is never an id, so
   * there is nothing a re-run of THIS stage would do differently — textual
   * mention linking (P-EP1) is a different lane's business.
   */
  unbound: number;
  /** Queue rows whose event no longer exists. Settled, not retried. */
  orphaned: number;
  /** In-band pairs parked for the batched agent lane. NOT adjudicated here. */
  pairsDeferred: number;
  /** Pairs sent to the human resolution queue — rung ⑤. */
  pairsQueued: number;
  /**
   * What the stream-roster half of the stage did — `participant_entity_ids`
   * and the group membership edges (`./stream-participants.ts`). Empty on
   * `drainEntityQueue`, which binds actors and nothing else: rosters are read
   * OFF bound actors, so they belong to the pass that has just finished
   * binding them rather than to one chunk of it.
   */
  rosters: StreamParticipantsReport;
  /**
   * Always 0, and typed as `0` so a future edit that reaches for a model has
   * to change the TYPE to do it. Identity resolution is `[CODE]` end to end;
   * rung ④ is parked, never called (§10.3 rule 6).
   */
  llmCalls: 0;
  errors: string[];
}

export function emptyEntityReport(): EntityDrainReport {
  return {
    claimed: 0,
    bound: 0,
    actorsResolved: 0,
    minted: 0,
    selfBound: 0,
    selfSources: 0,
    unbound: 0,
    orphaned: 0,
    pairsDeferred: 0,
    pairsQueued: 0,
    rosters: emptyStreamParticipantsReport(),
    llmCalls: 0,
    errors: [],
  };
}

interface EventRow {
  id: string;
  actor_id: string | null;
}

/**
 * Work the `entity` stage of the queue, highest priority first.
 *
 * SYNCHRONOUS ON PURPOSE. Every rung this stage can reach is `[CODE]`, so
 * there is no transport to await and no wallet to draw on — the cost guarantee
 * is the function's signature, not a comment. Callers in an async pipeline may
 * `await` it like any other stage.
 *
 * Each event is settled INDIVIDUALLY: a completed one is marked `done` inside
 * the loop, so a crash costs the in-flight event and leaves the rest in
 * `running` for `resumeQueue()` to hand back at `ready` (§9.7 rule 5). A row
 * that throws is retried on the queue's ladder and quarantined once
 * `ENTITY_MAX_ATTEMPTS` is spent, so one bad actor never stalls the backlog.
 */
export function drainEntityQueue(opts: EntityPassOptions & { limit?: number } = {}): EntityDrainReport {
  const now = opts.now ?? Date.now();
  const report = emptyEntityReport();

  // §10.3 rule 4, before a single actor is looked at: an actor resolved ahead
  // of `me` mints a second self and the merge that repairs it is a tombstone
  // every later roster read has to follow.
  try {
    report.selfSources = bindSelfIdentities().length;
  } catch (err) {
    report.errors.push(`self: ${err instanceof Error ? err.message : String(err)}`);
  }
  const me = meEntityId();

  const items: WorkItem[] = claimWork({
    stages: ["entity"],
    limit: Math.max(1, Math.floor(opts.limit ?? 256)),
    nowIso: new Date(now).toISOString(),
  });
  report.claimed = items.length;
  if (items.length === 0) return report;

  const readEvent = getDb().prepare(`SELECT id, actor_id FROM events WHERE id = ?`);
  // One resolution per ACTOR, replayed across its events. This is what turns a
  // 3,141-row backlog into 100 ladder walks.
  const resolved = new Map<string, ActorResolution | null>();

  for (const item of items) {
    try {
      if (item.unitKind !== "event") {
        report.errors.push(`${item.id}: stage entity received unit_kind ${item.unitKind}`);
        failWork(item.id, { action: "quarantine" });
        continue;
      }
      const event = readEvent.get(item.unitId) as EventRow | undefined;
      if (event === undefined) {
        report.orphaned += 1;
        completeWork(item.id);
        continue;
      }
      if (event.actor_id === null) {
        report.unbound += 1;
        completeWork(item.id);
        continue;
      }

      let actor = resolved.get(event.actor_id);
      if (actor === undefined) {
        actor = resolveActorEntity(event.actor_id, opts);
        resolved.set(event.actor_id, actor);
        if (actor !== null) {
          report.actorsResolved += 1;
          if (actor.minted) report.minted += 1;
          report.pairsDeferred += actor.deferred;
          report.pairsQueued += actor.queued;
        }
      }
      if (actor === null) {
        report.unbound += 1;
        completeWork(item.id);
        continue;
      }

      setEventActorEntity(event.id, actor.entityId);
      report.bound += 1;
      if (me !== null && actor.entityId === me) report.selfBound += 1;
      completeWork(item.id);
    } catch (err) {
      report.errors.push(`${item.unitId}: ${err instanceof Error ? err.message : String(err)}`);
      failWork(
        item.id,
        item.attempts >= ENTITY_MAX_ATTEMPTS
          ? { action: "quarantine" }
          : { action: "retry", notBeforeAt: new Date(now + 60_000).toISOString() },
      );
    }
  }

  log(
    `claimed=${report.claimed} bound=${report.bound} self=${report.selfBound} ` +
      `actors=${report.actorsResolved} minted=${report.minted} unbound=${report.unbound} ` +
      `pairs=${report.pairsDeferred}+${report.pairsQueued} llm=${report.llmCalls} ` +
      `errors=${report.errors.length}`,
  );
  return report;
}

/**
 * Sweep the backlog onto the queue and work it — the entry point a cohort tick
 * or a catch-up pass calls. `enqueueEntityWork` refuses to double-file an event
 * `tiers/rescan.ts` already queued, so this is safe to call over the same
 * events as often as it likes.
 *
 * THE ROSTER SWEEP RUNS LAST, AND UNCONDITIONALLY. `streams.participant_entity_ids`
 * and the `affiliated_with:member` edges are read off `events.actor_entity_id`,
 * so they can only be written once the drain above has filled it — and they are
 * NOT gated on the drain having claimed anything, because an install whose
 * events were all bound before `./stream-participants.ts` existed claims zero
 * and still owes 93 rosters. The sweep's own pending query decides; this
 * function only decides WHEN it is asked (§10.3: after actor binding, before a
 * session is sealed over the answer).
 *
 * Still free, still synchronous: `bindStreamParticipants` imports no transport
 * and reaches nothing above rung ②.
 */
export function entityPass(opts: EntityPassOptions & { limit?: number; cohortId?: string | null } = {}): EntityDrainReport {
  const limit = Math.max(1, Math.floor(opts.limit ?? 256));
  enqueueEntityWork(pendingEntityWork({ limit }), {
    cohortId: opts.cohortId ?? null,
    ...(opts.now === undefined ? {} : { now: opts.now }),
  });
  const { cohortId: _cohortId, ...rest } = opts;
  const report = drainEntityQueue({ ...rest, limit });
  try {
    report.rosters = bindStreamParticipants({ kindOf: identityKindOf });
  } catch (err) {
    report.errors.push(`rosters: ${err instanceof Error ? err.message : String(err)}`);
  }
  report.errors.push(...report.rosters.errors);
  return report;
}
