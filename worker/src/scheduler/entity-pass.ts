// ===========================================================================
// [CODE] The entity stage — the scheduler's caller for the resolution ladder.
// Arch §9.4 (Lane U's entry stage, beside `enrich`), §10.3 (the ladder itself,
// its rule 4 "the me entity" and its rule 6 "adjudication is batched").
//
// ⚠ THE DEFECT THIS FILE EXISTS FOR. `tiers/rescan.ts` has enqueued a row at
// stage `entity` for every event since item 1.2, and NOTHING HAS EVER CLAIMED
// ONE. `entities` stayed empty on a live install with 100 actors and 3,141
// queued events; `events.actor_entity_id` stayed NULL on every row; and every
// downstream reader that asks "who is `me` in this conversation" — the P-CL1
// participant roster above all — got an empty answer and mapped the
// COUNTERPARTY's words onto the user. A queue with no drainer does not fail
// loudly; it produces confident, wrong attribution.
//
// WHAT A PASS ACTUALLY DOES, per queued event:
//
//   * `bindSelfIdentities` first, once per drain — every source's persisted
//     `self_identity` binds into the ONE `me` entity (§10.3 rule 4) before any
//     actor is resolved. Order matters: an actor resolved before `me` exists
//     mints a second self, and the merge that repairs it is a tombstone the
//     roster then has to follow.
//   * the event's ACTOR is resolved through `resolveIdentity` — rungs ①
//     exact, ② cross-source, and MINT. All three are `[CODE]`. Resolution is
//     memoised per actor, which is what turns 3,141 events into 100 binds.
//   * `setEventActorEntity` writes `actor_entity_id` AND derives `is_self`.
//
// THE COST GUARANTEE IS STRUCTURAL, NOT A PROMISE. This module is entirely
// synchronous and imports no transport: there is no `await` for a provider to
// hide behind, so a pass over the whole backlog cannot bill a token. The
// [ML] rung is off whenever calibration is missing (`resolve.ts` decides that,
// not this file) and rung ④ is never CALLED here — an in-band pair is parked
// on the `AgentBatch` for the horizon boundary, which is §10.3 rule 6 read
// literally: "exact and cross-source binds apply immediately; in-band pairs
// accumulate and are adjudicated at horizon boundaries". `report.llmCalls` is
// the literal `0` that says so out loud.
//
// CANDIDATES ARE FREE AND EXACT. Only a MINT escalates (only a mint claims
// this is somebody new), and the candidates it is checked against are entities
// whose canonical name is the SAME normalised string — the "two Amits"
// question, generated by an indexed read rather than an embedding. Generating
// the candidate is free; deciding it is not, so the decision is deferred.
// ===========================================================================

